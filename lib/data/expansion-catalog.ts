function categoryById(id: string): ProductCategory {
  const found = EXPANSION_CATEGORIES.find((c) => c.id === id);
  if (!found) {
    throw new Error(`Missing expansion category ${id}`);
  }
  return found;
}

function product(input: Omit<Product, 'currency' | 'hasVariants' | 'variants' | 'lowStockThreshold' | 'technicalSpecifications' | 'images'> & {
  brand: string;
  stock: number;
  specs: Record<string, string>;
  image: string;
  merch?: string;
}): Product {
  return {
    id: input.id,
    name: input.name,
    slug: input.slug,
    sku: input.sku,
    categoryId: input.categoryId,
    category: input.category,
    brand: input.brand,
    shortDescription: input.shortDescription,
    description: input.description,
    basePrice: input.basePrice,
    currency: 'PKR',
    status: input.status,
    stock: input.stock,
    lowStockThreshold: 5,
    hasVariants: false,
    isFeatured: input.isFeatured,
    variants: [],
    images: [
      {
        id: `${input.id}-img-1`,
        url: input.image,
        alt: input.name,
        isPrimary: true,
        displayOrder: 1,
      },
    ],
    technicalSpecifications: {
      ...input.specs,
      ...(input.merch ? { Merch: input.merch } : {}),
    },
    compatibilityNotes: input.compatibilityNotes,
    shippingNotes: input.shippingNotes,
    createdAt: input.createdAt,
    updatedAt: input.updatedAt,
  };
}

